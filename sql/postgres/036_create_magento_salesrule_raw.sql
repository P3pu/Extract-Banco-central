CREATE TABLE IF NOT EXISTS raw.magento_salesrule (
    rule_id BIGINT PRIMARY KEY,
    name VARCHAR(255),
    description TEXT,
    from_date TEXT,
    to_date TEXT,
    uses_per_customer INTEGER NOT NULL,
    is_active INTEGER NOT NULL,
    conditions_serialized TEXT,
    actions_serialized TEXT,
    stop_rules_processing INTEGER NOT NULL,
    is_advanced INTEGER NOT NULL,
    product_ids TEXT,
    sort_order BIGINT NOT NULL,
    simple_action VARCHAR(32),
    discount_amount NUMERIC(12,4) NOT NULL,
    discount_qty NUMERIC(12,4),
    discount_step BIGINT NOT NULL,
    apply_to_shipping INTEGER NOT NULL,
    times_used BIGINT NOT NULL,
    is_rss INTEGER NOT NULL,
    coupon_type INTEGER NOT NULL,
    use_auto_generation INTEGER NOT NULL,
    uses_per_coupon INTEGER NOT NULL,
    updated_at TEXT,
    created_at TEXT,
    simple_free_shipping INTEGER NOT NULL,
    _source TEXT NOT NULL,
    _extracted_at TIMESTAMPTZ NOT NULL,
    _batch_id UUID NOT NULL
);
