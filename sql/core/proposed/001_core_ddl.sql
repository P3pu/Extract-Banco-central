-- Pré-requisitos: PostgreSQL 13+, schemas RAW/STAGING validados, backup e janela.
-- Nenhum objeto existente é removido. A aplicação deve registrar a versão aplicada.

BEGIN;

CREATE SCHEMA IF NOT EXISTS core;

CREATE TABLE core.dim_evento (
    evento_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    seed_origem TEXT NOT NULL CHECK (seed_origem IN ('ativo', 'magento')),
    seed_evento_id BIGINT NOT NULL,
    nome_evento TEXT,
    data_evento DATE,
    data_evento_original TEXT,
    sku_referencia TEXT,
    flag_evento_teste BOOLEAN NOT NULL DEFAULT FALSE,
    motivo_evento_teste TEXT,
    status_mapeamento TEXT NOT NULL DEFAULT 'INDIVIDUAL'
        CHECK (status_mapeamento IN ('INDIVIDUAL', 'UNIFICADO_VALIDADO', 'AMBIGUO')),
    data_atualizacao_core TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    CONSTRAINT dim_evento_seed_uk UNIQUE (seed_origem, seed_evento_id)
);

CREATE TABLE core.evento_source_map (
    origem TEXT NOT NULL CHECK (origem IN ('ativo', 'magento')),
    evento_id_origem BIGINT NOT NULL,
    evento_key BIGINT NOT NULL REFERENCES core.dim_evento(evento_key),
    sku_origem TEXT,
    criterio_vinculo TEXT NOT NULL DEFAULT 'ORIGEM'
        CHECK (criterio_vinculo IN ('ORIGEM', 'MANUAL_VALIDADO')),
    flag_ambiguidade BOOLEAN NOT NULL DEFAULT FALSE,
    revisado_por TEXT,
    revisado_em TIMESTAMPTZ,
    PRIMARY KEY (origem, evento_id_origem),
    CONSTRAINT evento_map_manual_checagem CHECK (
        criterio_vinculo <> 'MANUAL_VALIDADO'
        OR (revisado_por IS NOT NULL AND revisado_em IS NOT NULL)
    )
);
CREATE INDEX evento_source_map_evento_idx ON core.evento_source_map(evento_key);

CREATE TABLE core.dim_pessoa (
    pessoa_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cpf_token_seguro BYTEA,
    cpf_valido BOOLEAN,
    criterio_identificacao TEXT NOT NULL
        CHECK (criterio_identificacao IN ('CPF_VALIDO', 'SOURCE_ID')),
    criado_core_em TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    atualizado_core_em TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    CONSTRAINT dim_pessoa_token_checagem CHECK (
        (criterio_identificacao = 'CPF_VALIDO' AND cpf_valido IS TRUE
         AND cpf_token_seguro IS NOT NULL
         AND octet_length(cpf_token_seguro) = 32)
        OR (criterio_identificacao = 'SOURCE_ID' AND cpf_token_seguro IS NULL)
    )
);
CREATE UNIQUE INDEX dim_pessoa_cpf_token_uk
    ON core.dim_pessoa(cpf_token_seguro) WHERE cpf_token_seguro IS NOT NULL;

CREATE TABLE core.pessoa_source_map (
    origem TEXT NOT NULL CHECK (origem IN ('ativo', 'magento')),
    tipo_identificador TEXT NOT NULL
        CHECK (tipo_identificador IN ('Usuario', 'UsuarioBalcao', 'Customer')),
    id_pessoa_origem BIGINT NOT NULL,
    pessoa_key BIGINT NOT NULL REFERENCES core.dim_pessoa(pessoa_key),
    papel_verificado TEXT CHECK (papel_verificado IN ('COMPRADOR', 'PARTICIPANTE', 'AMBOS')),
    criterio_vinculo TEXT NOT NULL CHECK (criterio_vinculo IN ('CPF_VALIDO', 'SOURCE_ID')),
    flag_ambiguidade BOOLEAN NOT NULL DEFAULT FALSE,
    PRIMARY KEY (origem, tipo_identificador, id_pessoa_origem)
);
CREATE INDEX pessoa_source_map_pessoa_idx ON core.pessoa_source_map(pessoa_key);

CREATE TABLE core.dim_combo (
    combo_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    origem TEXT NOT NULL CHECK (origem IN ('ativo', 'magento')),
    combo_id_origem TEXT NOT NULL,
    nome_combo TEXT,
    qtd_inscricoes_previstas INTEGER CHECK (qtd_inscricoes_previstas > 0),
    flag_composicao_validada BOOLEAN NOT NULL DEFAULT FALSE,
    atualizado_core_em TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    CONSTRAINT dim_combo_origem_uk UNIQUE (origem, combo_id_origem),
    CONSTRAINT dim_combo_composicao_checagem CHECK (
        flag_composicao_validada IS FALSE OR qtd_inscricoes_previstas IS NOT NULL
    )
);

CREATE TABLE core.fato_pedido (
    pedido_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    origem TEXT NOT NULL CHECK (origem IN ('ativo', 'magento')),
    pedido_id_origem BIGINT NOT NULL,
    protocolo TEXT,
    comprador_id_origem BIGINT,
    comprador_key BIGINT REFERENCES core.dim_pessoa(pessoa_key),
    data_pedido TIMESTAMP,
    data_pedido_original TEXT,
    data_atualizacao_origem TIMESTAMP,
    data_atualizacao_original TEXT,
    status_pedido_origem TEXT,
    estado_pedido_origem TEXT,
    status_pedido_codigo INTEGER,
    local_inscricao_codigo INTEGER,
    status_corporativo TEXT NOT NULL
        CHECK (status_corporativo IN ('CANCELADO', 'CONFIRMADO', 'PENDENTE', 'NOVO', 'INDETERMINADO')),
    flag_cancelado BOOLEAN,
    pagamento_confirmado BOOLEAN,
    valor_bruto_pedido NUMERIC(20,4),
    desconto_pedido_origem NUMERIC(20,4),
    valor_liquido_pedido NUMERIC(20,4),
    frete_pedido NUMERIC(20,4),
    imposto_pedido NUMERIC(20,4),
    valor_total_cobrado NUMERIC(20,4),
    taxa_adicional_operacional NUMERIC(20,4),
    taxa_servico_total_ativo NUMERIC(20,4),
    desconto_itens_identificado NUMERIC(20,4),
    desconto_nao_atribuido NUMERIC(20,4),
    flag_excecao_financeira BOOLEAN NOT NULL DEFAULT FALSE,
    flag_pedido_misto_teste BOOLEAN,
    bruto_comercial_apuravel BOOLEAN,
    batch_id_origem UUID,
    conteudo_hash TEXT NOT NULL,
    atualizado_core_em TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    CONSTRAINT fato_pedido_origem_uk UNIQUE (origem, pedido_id_origem)
);
CREATE INDEX fato_pedido_data_idx ON core.fato_pedido(data_pedido, origem);
CREATE INDEX fato_pedido_comprador_idx ON core.fato_pedido(comprador_key)
    WHERE comprador_key IS NOT NULL;

CREATE TABLE core.fato_inscricao (
    inscricao_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    origem TEXT NOT NULL CHECK (origem IN ('ativo', 'magento')),
    inscricao_id_origem BIGINT NOT NULL,
    pedido_id_origem BIGINT,
    pedido_key BIGINT REFERENCES core.fato_pedido(pedido_key),
    evento_id_origem BIGINT,
    evento_key BIGINT REFERENCES core.dim_evento(evento_key),
    participante_id_origem BIGINT,
    participante_key BIGINT REFERENCES core.dim_pessoa(pessoa_key),
    combo_key BIGINT REFERENCES core.dim_combo(combo_key),
    data_evento DATE,
    data_evento_original TEXT,
    sku_evento_origem TEXT,
    sku_inscricao_magento TEXT,
    modalidade_id_origem TEXT,
    modalidade_origem TEXT,
    modalidade_padronizada TEXT,
    categoria_id_origem TEXT,
    categoria_nome_origem TEXT,
    tamanho_id_origem TEXT,
    tamanho_origem TEXT,
    tamanho_padronizado TEXT,
    status_pedido_origem TEXT,
    status_individual_codigo INTEGER,
    status_individual_origem TEXT,
    flag_cancelado_inscricao BOOLEAN,
    contabiliza_inscricao BOOLEAN,
    contabiliza_bruto BOOLEAN,
    pagamento_confirmado BOOLEAN,
    pagamento_presumido BOOLEAN,
    pago_considerado BOOLEAN,
    motivo_elegibilidade TEXT,
    classificacao_venda TEXT CHECK (classificacao_venda IN ('Grupos', 'Cortesia', 'Site')),
    motivo_classificacao TEXT,
    regras_classificacao JSONB,
    cupom_codigo_origem TEXT,
    classificacao_cupom_ativo TEXT,
    valor_bruto_inscricao NUMERIC(20,4),
    desconto_individual_original TEXT,
    desconto_individual_origem NUMERIC(20,4),
    valor_kit_ativo NUMERIC(20,4),
    desconto_filhos_magento NUMERIC(20,4),
    desconto_pai_magento NUMERIC(20,4),
    desconto_aplicado_inscricao NUMERIC(20,4),
    valor_liquido_itens NUMERIC(20,4),
    valor_liquido_inscricao NUMERIC(20,4),
    liquido_individual_conciliado BOOLEAN,
    taxa_servico_ativo NUMERIC(20,4),
    quantidade_pedida NUMERIC(20,4),
    quantidade_cancelada NUMERIC(20,4),
    quantidade_reembolsada NUMERIC(20,4),
    flag_evento_teste BOOLEAN,
    flag_pedido_nao_encontrado BOOLEAN NOT NULL,
    flag_evento_nao_mapeado BOOLEAN NOT NULL,
    flag_excecao_financeira BOOLEAN,
    estado_derivacao TEXT NOT NULL DEFAULT 'PENDENTE'
        CHECK (estado_derivacao IN ('PENDENTE', 'VALIDADO', 'BLOQUEADO')),
    derivado_de_hash TEXT,
    -- Reservados para o reconciliador de dependências, ainda não implementado.
    -- O hash básico NÃO cobre status, finanças, cupom, cadastros ou regras.
    dependencias_hash_snapshot TEXT,
    derivado_de_dependencias_hash TEXT,
    versao_regras_derivacao TEXT,
    derivado_em DATE,
    batch_id_origem UUID,
    conteudo_hash TEXT NOT NULL,
    atualizado_core_em TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    CONSTRAINT fato_inscricao_derivacao_checagem CHECK (
        estado_derivacao <> 'VALIDADO'
        OR (derivado_de_hash IS NOT NULL AND derivado_de_hash = conteudo_hash
            AND dependencias_hash_snapshot IS NOT NULL
            AND derivado_de_dependencias_hash IS NOT NULL
            AND derivado_de_dependencias_hash = dependencias_hash_snapshot
            AND versao_regras_derivacao IS NOT NULL
            AND derivado_em IS NOT NULL)
    ),
    CONSTRAINT fato_inscricao_origem_uk UNIQUE (origem, inscricao_id_origem)
);
CREATE INDEX fato_inscricao_pedido_idx ON core.fato_inscricao(origem, pedido_id_origem);
CREATE INDEX fato_inscricao_evento_idx ON core.fato_inscricao(evento_key)
    WHERE evento_key IS NOT NULL;
CREATE INDEX fato_inscricao_pendente_idx ON core.fato_inscricao(data_evento)
    WHERE pagamento_presumido IS FALSE AND flag_cancelado_inscricao IS FALSE;

CREATE TABLE core.core_etl_execucao (
    execucao_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id UUID NOT NULL UNIQUE,
    versao_ddl TEXT NOT NULL CHECK (versao_ddl ~ '^CORE_[A-Z0-9_.-]{1,64}$'),
    escopo TEXT NOT NULL CHECK (escopo IN
        ('DIM_EVENTO', 'DIM_COMBO', 'PEDIDO_MAGENTO', 'PEDIDO_ATIVO',
         'INSCRICAO_BASE', 'INSCRICAO_DERIVADA', 'RECONCILIACAO', 'VALIDACAO')),
    iniciada_em TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    encerrada_em TIMESTAMPTZ,
    status TEXT NOT NULL CHECK (status IN ('RUNNING', 'SUCCEEDED', 'FAILED')),
    linhas_inseridas BIGINT NOT NULL DEFAULT 0,
    linhas_atualizadas BIGINT NOT NULL DEFAULT 0,
    erro_codigo TEXT CHECK (erro_codigo IS NULL OR erro_codigo IN
        ('FONTE_INDISPONIVEL', 'SCHEMA_DIVERGENTE', 'LOTE_INVALIDO',
         'CONSTRAINT', 'TIMEOUT', 'RECONCILIACAO', 'ERRO_INTERNO')),
    CONSTRAINT execucao_contadores_checagem CHECK (linhas_inseridas >= 0 AND linhas_atualizadas >= 0)
);

CREATE TABLE core.core_alerta_qualidade (
    alerta_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id UUID,
    origem TEXT CHECK (origem IN ('ativo', 'magento')),
    entidade TEXT NOT NULL CHECK (entidade IN ('pedido', 'inscricao', 'evento', 'pessoa', 'combo')),
    identificador_origem BIGINT CHECK (identificador_origem > 0),
    codigo_regra TEXT NOT NULL CHECK (codigo_regra IN
        ('ORFAO_PEDIDO', 'EVENTO_SEM_MAPA', 'DESCONTO_CABECALHO',
         'DESCONTO_INVALIDO', 'DATA_INVALIDA', 'CUPOM_HEADER_AUSENTE',
         'STATUS_CONTRADITORIO', 'STATUS_ESPECIAL', 'QTD_BUNDLE',
         'CANCELAMENTO_PARCIAL', 'REEMBOLSO', 'CPF_INVALIDO',
         'CPF_PAPEL_NAO_VALIDADO', 'COMBO_COMPOSICAO',
         'VALOR_NAO_CONCILIADO')),
    severidade TEXT NOT NULL CHECK (severidade IN ('INFO', 'WARNING', 'BLOCKER')),
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    resolvido_em TIMESTAMPTZ
);
CREATE UNIQUE INDEX core_alerta_ativo_uk
    ON core.core_alerta_qualidade(
        COALESCE(origem,''), entidade, COALESCE(identificador_origem,-1), codigo_regra)
    WHERE ativo;
CREATE INDEX core_alerta_batch_idx ON core.core_alerta_qualidade(batch_id);

-- O dono da migração deve criar papéis e grants mínimos em etapa separada.
-- Nenhuma permissão de leitura de dim_pessoa/pessoa_source_map deve ir ao BI.
-- Alerta armazena somente código de regra e PK numérica da entidade. Jamais
-- guardar CPF, nome, e-mail, mensagem livre ou exceção bruta do driver.
REVOKE ALL ON core.dim_pessoa, core.pessoa_source_map FROM PUBLIC;

CREATE VIEW core.fato_inscricao_indicadores_validos AS
SELECT * FROM core.fato_inscricao
-- Gate fechado nesta proposta: não há reconciliador de TODAS as dependências.
-- Remover FALSE somente em migração aprovada, após invalidação transacional,
-- versionamento de regras e teste de mudanças em fontes auxiliares.
WHERE FALSE
  AND estado_derivacao = 'VALIDADO'
  AND derivado_de_hash = conteudo_hash
  AND derivado_de_dependencias_hash = dependencias_hash_snapshot
  AND versao_regras_derivacao IS NOT NULL
  AND (data_evento IS NULL
       OR pagamento_confirmado IS TRUE
       OR pagamento_presumido IS TRUE
       OR data_evento >= (now() AT TIME ZONE 'America/Sao_Paulo')::DATE
       OR derivado_em > data_evento);
-- Pendente calculada antes/no dia do evento fica invisível no dia seguinte,
-- até recálculo. Histórico estável não exige varredura integral diária.
COMMIT;
