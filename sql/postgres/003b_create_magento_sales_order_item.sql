-- Contrato validado na origem em 2026-09-28. ozone_customers permanece TEXT.
CREATE TABLE IF NOT EXISTS raw.magento_sales_order_item (
    item_id BIGINT PRIMARY KEY,
    order_id BIGINT NOT NULL,
    parent_item_id BIGINT,
    product_id BIGINT,
    sku VARCHAR(255),
    name VARCHAR(255),
    product_type VARCHAR(255),
    additional_data TEXT,
    ext_order_item_id VARCHAR(255),
    ozone_customers TEXT,
    price NUMERIC(12,4) NOT NULL,
    base_price NUMERIC(12,4) NOT NULL,
    row_total NUMERIC(20,4) NOT NULL,
    base_row_total NUMERIC(20,4) NOT NULL,
    discount_amount NUMERIC(20,4),
    base_discount_amount NUMERIC(20,4),
    tax_amount NUMERIC(20,4),
    base_tax_amount NUMERIC(20,4),
    qty_ordered NUMERIC(12,4),
    qty_invoiced NUMERIC(12,4),
    qty_canceled NUMERIC(12,4),
    qty_refunded NUMERIC(12,4),
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    _source TEXT NOT NULL,
    _extracted_at TIMESTAMPTZ NOT NULL,
    _batch_id UUID NOT NULL
);
